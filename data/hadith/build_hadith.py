BOOKS = ["muslim", "abudawud", "tirmidhi", "nasai", "ibnmajah"]

for b in BOOKS:
    ara = json.load(open(f"{SRC}/ara-{b}.json"))
    eng = json.load(open(f"{SRC}/eng-{b}.json"))
    eng_by_n = {h["hadithnumber"]: h for h in eng["hadiths"]}
    sections = {}
    hadiths = []
    for h in ara["hadiths"]:
        n = h["hadithnumber"]
        ar = (h["text"] or "").strip()
        eh = eng_by_n.get(n, {})
        en = ((eh.get("text") or "").strip())
        if not ar and not en:
            continue
        s = h["reference"]["book"]
        hadiths.append({"n": n, "s": s, "ar": ar, "en": en})
    # sections with counts
    sec_meta = ara["metadata"]["sections"]
    counts = {}
    for hh in hadiths:
        counts[hh["s"]] = counts.get(hh["s"], 0) + 1
    for k, name in sec_meta.items():
        k = int(k)
        en_name = name.strip() if name.strip() else "General"
        tr_name = TR.get(name.strip(), en_name)
        sections[str(k)] = {"en": en_name, "tr": tr_name, "n": counts.get(k, 0)}
    # section 0 catch-all like bukhari
    if "0" not in sections and 0 in counts:
        sections["0"] = {"en": "General", "tr": "Genel", "n": counts[0]}
    out = {
        "book": b,
        "sections": sections,
        "hadiths": hadiths,
        "attribution": "Arabic: public domain (Shamela). English: hadith-api edition (fawazahmed0); translator credits vary by book.",
    }
    op = f"{OUT}/{b}.json"
    json.dump(out, open(op, "w"), ensure_ascii=False, separators=(",", ":"))
    sz = os.path.getsize(op)
    missing_tr = [k for k, v in sections.items() if v["tr"] == v["en"] and v["en"] != "General"]
    print(f"{b}: {len(hadiths)} hadiths, {len(sections)} sections, {sz/1048576:.1f} MB, untranslated sections: {len(missing_tr)}")
    for k in missing_tr[:6]:
        print("   MISSING:", sections[k]["en"])
